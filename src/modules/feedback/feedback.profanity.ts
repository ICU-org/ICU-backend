/*
 * Словарь мата для выгрузки в мэрию (docs/architecture.md §6a, §6c): в файле
 * такое слово заменяется на ***, в БД остаётся оригинал. Каждый шаблон
 * проверяется с начала слова — иначе «страхует» ловился бы по «хуе».
 * Слово сравнивается в нижнем регистре, «ё» → «е». Список стартовый:
 * дополнять по мере того, что реально приходит.
 */

// приставки, с которыми русский мат встречается чаще всего; без «в» и «с» —
// иначе «вебинар», «себе» попадали бы под «еб»
const RU_PREFIX = "(?:за|на|по|от|вы|у|съ|въ|раз|рас|под|пере|недо|до|при|об|о|ни)?";

const PATTERNS: RegExp[] = [
  // русский
  new RegExp(`^${RU_PREFIX}(?:ху[йеяюи]|пизд|еб[аулнеи]|муд[аои]|пид[оа]р|залуп|гандон|шлюх)`),
  new RegExp(`^${RU_PREFIX}бля(?:д|т|$)`),
  /^сук(?:а|и|е|у|ой|ами|ам|ах|ин)/,
  // английский
  /^(?:mother)?fuck|^shit|^bitch|^cunt|^asshole|^whore|^slut|^bastard/,
  // армянский — армянским алфавитом
  /^քուն(?:ե[մսլք]|ի|ա[ծց]|վ)/,
  /^բոզ/,
  /^պոռնիկ/,
  /^քաք/,
  /^գյոթ/,
  // армянский — латиницей (ը часто пишут как @)
  /^[qk]une[mslq]/,
  /^[qk]una[ct]/,
  /^[qk]uni$/,
  /^boz(?:i|y|@|ik|er)?$/,
  /^pornik/,
  /^qaq/,
  /^gyot/,
  // армянский — кириллицей
  /^(?:к|кх)уне[мсл]/,
  /^куна[цт]/,
  /^боз(?:и|ы|ик)?$/,
  /^порник/,
];

// слово: буквы любого алфавита, диакритика, цифры и @
const WORD = /[\p{L}\p{M}\p{N}@]+/gu;

export function maskProfanity(text: string): string {
  return text.replace(WORD, (word) => {
    const normalized = word.toLowerCase().replace(/ё/g, "е");
    return PATTERNS.some((re) => re.test(normalized)) ? "***" : word;
  });
}
